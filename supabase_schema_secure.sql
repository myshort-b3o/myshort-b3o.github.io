-- =========================================================
-- 6) Pembelian AI-MAX: hanya RPC yang dapat mengaktifkan.
--    Saldo Rp100.000 dipotong secara atomik.
-- =========================================================
create or replace function public.purchase_ai_max()
returns bigint
language plpgsql
security definer
set search_path=public
as $$
declare
  uid uuid:=auth.uid();
  pid bigint;
begin
  if uid is null then raise exception 'Belum login'; end if;

  if exists(
    select 1 from public.ai_max_purchases
    where user_id=uid and active=true
  ) then
    raise exception 'AI-MAX Anda masih aktif';
  end if;

  perform 1 from public.wallets where user_id=uid for update;
  if not found then raise exception 'Wallet tidak ditemukan'; end if;

  update public.wallets
  set balance=balance-100000,
      total_out=total_out+100000,
      updated_at=now()
  where user_id=uid and balance>=100000;

  if not found then raise exception 'Saldo tidak mencukupi. Deposit minimal Rp100.000 terlebih dahulu'; end if;

  insert into public.ai_max_purchases(user_id,price,daily_reward,active)
  values(uid,100000,8000,true)
  returning id into pid;

  -- Jika user ini datang dari referral, referral baru dianggap VALID
  -- setelah pembelian AI-MAX berhasil tercatat.
  update public.referrals
  set status='qualified', reward=0
  where referred_id=uid;

  insert into public.transactions(user_id,type,amount,reference_id,description)
  values(uid,'ai_max_purchase',100000,pid,'Pembelian AI-MAX Rp100.000');

  return pid;
end;
$$;

-- =========================================================
-- 7) Klaim AI-MAX harian: server time Asia/Jakarta.
--    Hanya 12:00 sampai sebelum 24:00 dan satu kali/hari.
--    Kepemilikan AI-MAX wajib ada; tanpa pembelian tidak ada klaim.
-- =========================================================
create or replace function public.claim_ai_max_daily_reward()
returns numeric
language plpgsql
security definer
set search_path=public
as $$
declare
  uid uuid:=auth.uid();
  local_now timestamp;
  local_date date;
  purchase public.ai_max_purchases;
  claim_id bigint;
  reward numeric:=8000;
begin
  if uid is null then raise exception 'Belum login'; end if;

  local_now:=timezone('Asia/Jakarta',now());
  local_date:=local_now::date;

  if local_now < (local_date::timestamp + interval '12 hours')
     or local_now >= ((local_date + 1)::timestamp) then
    raise exception 'Hadiah harian hanya dapat diklaim pukul 12.00-24.00 WIB';
  end if;

  select * into purchase
  from public.ai_max_purchases
  where user_id=uid and active=true
  order by purchased_at desc
  limit 1
  for update;

  if not found then raise exception 'AI-MAX belum aktif'; end if;

  insert into public.ai_max_daily_claims(user_id,purchase_id,claim_date,amount)
  values(uid,purchase.id,local_date,reward)
  on conflict(user_id,claim_date) do nothing
  returning id into claim_id;

  if claim_id is null then
    raise exception 'Hadiah hari ini sudah diklaim';
  end if;

  update public.wallets
  set balance=balance+reward,
      total_in=total_in+reward,
      updated_at=now()
  where user_id=uid;

  if not found then raise exception 'Wallet tidak ditemukan'; end if;

  insert into public.transactions(user_id,type,amount,reference_id,description)
  values(uid,'ai_max_daily_reward',reward,claim_id,'Hadiah harian AI-MAX');

  update public.profiles
  set xp=xp+8,updated_at=now()
  where id=uid;

  return reward;
end;
$$;

-- Backfill referral lama: jika referred sudah pernah membeli AI-MAX,
-- ubah status menjadi qualified. Ini tidak memberi bonus otomatis.
update public.referrals r
set status='qualified'
where r.status <> 'qualified'
  and exists (select 1 from public.ai_max_purchases p where p.user_id=r.referred_id);

-- =========================================================
-- 8) Referral 3 teman: valid hanya jika akun referred sudah
--    membeli AI-MAX Rp100.000. Verifikasi email saja tidak cukup.
--    Hadiah Rp30.000 satu kali.
-- =========================================================
create or replace function public.claim_referral_reward()
returns numeric
language plpgsql
security definer
set search_path=public
as $$
declare
  uid uuid:=auth.uid();
  cnt integer;
  reward numeric:=30000;
begin
  if uid is null then raise exception 'Belum login'; end if;

  if exists(
    select 1 from public.referral_reward_claims
    where user_id=uid and milestone=3
  ) then
    raise exception 'Hadiah referral Rp30.000 sudah diklaim';
  end if;

  select count(*)::int into cnt
  from public.referrals r
  join auth.users u on u.id=r.referred_id
  where r.referrer_id=uid
    and r.status='qualified'
    and u.email_confirmed_at is not null
    and exists (
      select 1 from public.ai_max_purchases p
      where p.user_id=r.referred_id
    );

  if cnt < 3 then
    raise exception 'Anda baru memiliki % dari 3 teman yang sudah membeli AI-MAX',cnt;
  end if;

  insert into public.referral_reward_claims(user_id,milestone,amount)
  values(uid,3,reward)
  on conflict(user_id,milestone) do nothing;

  if not found then
    raise exception 'Hadiah referral sudah diproses';
  end if;

  update public.wallets
  set balance=balance+reward,
      total_in=total_in+reward,
      updated_at=now()
  where user_id=uid;

  if not found then raise exception 'Wallet tidak ditemukan'; end if;

  insert into public.transactions(user_id,type,amount,description)
  values(uid,'referral_reward',reward,'Hadiah referral 3 teman pembeli AI-MAX');

  update public.profiles
  set xp=xp+30,updated_at=now()
  where id=uid;

  return reward;
end;
$$;

